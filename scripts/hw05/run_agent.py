"""Run a bounded local Ollama rental conversation with required JSONL evidence."""

import argparse
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from src.tool_agent import AgentLogError, run_agent

EXPLANATIONS = {
    "safety_block": "The executor blocked disclosure of private rental contact information.",
    "max_steps": "The response budget was reached before a final model answer.",
    "model_error": "The local model could not complete the request.",
    "malformed_response": "The model returned an invalid native response or tool batch.",
    "tool_error": "The rental executor could not return a valid result.",
}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("user_input")
    parser.add_argument("--model", required=True, help="Installed local Ollama tag; no hosted model")
    parser.add_argument("--base-url", default="http://127.0.0.1:11434")
    parser.add_argument("--max-steps", type=int, default=4)
    parser.add_argument("--timeout", type=float, default=60.0)
    parser.add_argument("--temperature", type=float, default=0.0)
    parser.add_argument("--log-path", type=Path)
    args = parser.parse_args(argv)
    try:
        result = run_agent(args.user_input, model_name=args.model, base_url=args.base_url,
                           max_steps=args.max_steps, timeout=args.timeout,
                           temperature=args.temperature, log_path=args.log_path)
    except (ValueError, AgentLogError) as exc:
        # These messages are generated by our configuration/logging boundaries.
        print(f"Agent could not run: {exc}", file=sys.stderr)
        return 2
    print(f"run_id={result.run_id} stop_reason={result.stop_reason} "
          f"steps={result.steps} tool_calls={result.tool_calls}")
    if result.stop_reason == "completed":
        print(result.answer)
        return 0
    print(EXPLANATIONS[result.stop_reason])
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
